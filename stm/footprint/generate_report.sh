#!/usr/bin/env bash
# Generates FOOTPRINT.md from the .o files this directory's Makefile
# just built. Run via `make report`, not directly (needs build/*.o).
set -euo pipefail
cd "$(dirname "$0")"

SIZE=arm-none-eabi-size
NM=arm-none-eabi-nm

{
  echo "# STM32 adapter flash/RAM footprint"
  echo
  echo "Generated by \`make -C stm/footprint report\` against a real ARM cross-compiler"
  echo "(\`$($SIZE --version | head -1)\`), \`-mcpu=cortex-m4 -Os\`. Each adapter \`.c\` file"
  echo "is compiled standalone to a \`.o\` (never linked into a full firmware image - no"
  echo "vendor SDK is installed in this environment) against the same fake STM32 HAL"
  echo "header \`../tests/fakes/\` uses for unit testing, since compiling only needs"
  echo "declarations, not its behavioral body. See \"What these numbers do and don't"
  echo "mean\" below before quoting one out of context."
  echo
  echo "| Peripheral | .text (flash, bytes) | .data (bytes) | .bss (RAM, bytes) |"
  echo "|---|---:|---:|---:|"

  total_text=0
  for f in build/*.o; do
    [ -e "$f" ] || continue
    name=$(basename "$f" .o)
    periph=$(echo "$name" | tr '[:lower:]' '[:upper:]')
    read -r text data bss _ _ <<< "$($SIZE "$f" | tail -1)"
    total_text=$((total_text + text))
    echo "| $periph | $text | $data | $bss |"
  done

  echo
  echo "Sum of all 8 adapters' \`.text\`: **${total_text} bytes** - a real project only"
  echo "ever includes the peripherals it actually uses, so treat this as a ceiling, not"
  echo "a typical build. Useful as a regression baseline: re-run after changing an"
  echo "adapter and diff against a committed copy of this file."
  echo
  echo "## Largest functions per adapter (\`nm --size-sort\`, top 3 each)"
  echo
  for f in build/*.o; do
    [ -e "$f" ] || continue
    name=$(basename "$f" .o)
    echo "### $name"
    echo '```'
    $NM --print-size --size-sort --radix=d "$f" 2>/dev/null | tail -3 | tac | awk '{printf "%6d bytes  %s\n", $2+0, $4}' || true
    echo '```'
  done

  echo
  echo "## What these numbers do and don't mean"
  echo
  echo "- **Real compiler, real target ISA (Cortex-M4), real -Os.** This is genuinely"
  echo "  how much flash each adapter's code costs - not a host-machine proxy."
  echo "- **No vendor SDK is linked in.** Every \`HAL_*\` call the adapter makes resolves"
  echo "  to an external symbol with zero bytes charged here - the real STM32 HAL's own"
  echo "  flash cost is NOT included. These numbers are the wrapper adapter's *own* code"
  echo "  only, the same scope this project's contract covers."
  echo "- **No linker garbage collection was run** (\`--gc-sections\` needs a full link),"
  echo "  so a function only reachable from an unused code path (e.g. the async tier, if"
  echo "  your project only calls the blocking one) is still counted here - real"
  echo "  firmware with \`--gc-sections\` enabled would drop it."
  echo "- **.bss (RAM) is per-adapter static state** (ring buffers, busy flags, callback"
  echo "  pointers) - real total RAM also depends on your linker script and whatever"
  echo "  else runs on the same part."
} > FOOTPRINT.md

echo "Wrote stm/footprint/FOOTPRINT.md"
