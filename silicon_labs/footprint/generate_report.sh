#!/usr/bin/env bash
# Generates FOOTPRINT.md from the .o files this directory's Makefile
# just built. Run via `make report`, not directly (needs build/*.o).
set -euo pipefail
cd "$(dirname "$0")"

SIZE=arm-none-eabi-size
NM=arm-none-eabi-nm

{
  echo "# Silicon Labs adapter flash/RAM footprint"
  echo
  echo "Generated by \`make -C silicon_labs/footprint report\` against a real ARM"
  echo "cross-compiler (\`$($SIZE --version | head -1)\`), \`-Os\`. Each adapter \`.c\` file"
  echo "is compiled standalone to a \`.o\` (never linked into a full firmware image - no"
  echo "vendor SDK is installed in this environment) against the same fake emlib/"
  echo "sl_gpio/sl_i2c/IADC headers \`../tests/fakes/\` uses for unit testing, since"
  echo "compiling only needs declarations, not their behavioral bodies. Covers both"
  echo "target macros this vendor ships - classic emlib (\`TARGET_SILABS\`, Cortex-M4)"
  echo "and the current sl_gpio/sl_i2c/IADC drivers (\`TARGET_SILABS_SLGPIO\`,"
  echo "Cortex-M33 - Series 2/3 parts use the M33 core). See \"What these numbers do"
  echo "and don't mean\" below before quoting one out of context."
  echo
  echo "| Generation | Core | Peripheral | .text (flash, bytes) | .data (bytes) | .bss (RAM, bytes) |"
  echo "|---|---|---|---:|---:|---:|"

  total_text=0
  for f in build/gpio.o build/uart.o build/i2c.o build/spi.o build/adc.o; do
    [ -e "$f" ] || continue
    name=$(basename "$f" .o)
    periph=$(echo "$name" | tr '[:lower:]' '[:upper:]')
    read -r text data bss _ _ <<< "$($SIZE "$f" | tail -1)"
    total_text=$((total_text + text))
    echo "| classic (emlib) | Cortex-M4 | $periph | $text | $data | $bss |"
  done
  for f in build/slgpio_gpio.o build/slgpio_uart.o build/slgpio_i2c.o build/slgpio_spi.o build/slgpio_adc.o; do
    [ -e "$f" ] || continue
    name=$(basename "$f" .o | sed 's/^slgpio_//')
    periph=$(echo "$name" | tr '[:lower:]' '[:upper:]')
    read -r text data bss _ _ <<< "$($SIZE "$f" | tail -1)"
    total_text=$((total_text + text))
    echo "| current (sl_gpio/sl_i2c/IADC) | Cortex-M33 | $periph | $text | $data | $bss |"
  done

  echo
  echo "Sum of all 14 adapters' \`.text\`: **${total_text} bytes** - no real project"
  echo "enables both generations at once (you pick one target macro), so treat this as"
  echo "a ceiling, not a typical build. Useful as a regression baseline: re-run after"
  echo "changing an adapter and diff against a committed copy of this file."
  echo
  echo "## Largest functions per adapter (\`nm --size-sort\`, top 3 each)"
  echo
  for f in build/*.o; do
    [ -e "$f" ] || continue
    name=$(basename "$f" .o)
    echo "### $name"
    echo '```'
    $NM --print-size --size-sort --radix=d "$f" 2>/dev/null | tail -3 | tac | awk '{printf "%6d bytes  %s\n", $2+0, $4}' || true
    echo '```'
  done

  echo
  echo "## What these numbers do and don't mean"
  echo
  echo "- **Real compiler, real target ISA, real -Os.** This is genuinely how much"
  echo "  flash each adapter's code costs on the core listed - not a host-machine proxy."
  echo "- **No vendor SDK is linked in.** Every \`GPIO_*\`/\`USART_*\`/\`I2C_*\`/\`ADC_*\`/"
  echo "  \`sl_gpio_*\`/\`sl_i2c_*\`/\`IADC_*\`/\`SPIDRV_*\` call the adapter makes resolves"
  echo "  to an external symbol with zero bytes charged here - the real Simplicity SDK's"
  echo "  own flash cost is NOT included. These numbers are the wrapper adapter's *own*"
  echo "  code only, the same scope this project's contract covers."
  echo "- **No linker garbage collection was run** (\`--gc-sections\` needs a full link),"
  echo "  so a function only reachable from an unused code path (e.g. the async tier, if"
  echo "  your project only calls the blocking one) is still counted here - real"
  echo "  firmware with \`--gc-sections\` enabled would drop it."
  echo "- **.bss (RAM) is per-adapter static state** (ring buffers, busy flags, callback"
  echo "  pointers) - real total RAM also depends on your linker script and whatever"
  echo "  else runs on the same part."
  echo "- Compare classic vs. current loosely, not directly - Cortex-M4 and Cortex-M33"
  echo "  have different instruction encodings and calling conventions, so a smaller"
  echo "  number on one core isn't automatically \"more efficient\" than the other."
} > FOOTPRINT.md

echo "Wrote silicon_labs/footprint/FOOTPRINT.md"
